def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description='Train Attention U-Net for KDA Prediction'
    )

    # Data
    parser.add_argument('--data_dir', type=str, required=True,
                        help='Path to KDA training data')
    parser.add_argument('--output_dir', type=str, default='./checkpoints/kda',
                        help='Output directory for checkpoints')

    # Model
    parser.add_argument('--base_filters', type=int, default=64,
                        help='Base filter count')
    parser.add_argument('--attention_filters', type=int, default=256,
                        help='Attention gate filter count')
    parser.add_argument('--dropout', type=float, default=0.1,
                        help='Dropout rate')

    # Training
    parser.add_argument('--epochs', type=int, default=100,
                        help='Number of training epochs')
    parser.add_argument('--batch_size', type=int, default=8,
                        help='Batch size')
    parser.add_argument('--lr', type=float, default=1e-4,
                        help='Learning rate')
    parser.add_argument('--weight_decay', type=float, default=1e-5,
                        help='Weight decay')
    parser.add_argument('--patience', type=int, default=20,
                        help='Early stopping patience')

    # Loss weights
    parser.add_argument('--bce_weight', type=float, default=1.0,
                        help='BCE loss weight')
    parser.add_argument('--dice_weight', type=float, default=1.0,
                        help='Dice loss weight')

    # Other
    parser.add_argument('--num_workers', type=int, default=4,
                        help='DataLoader workers')
    parser.add_argument('--device', type=str, default=None,
                        help='Device (cuda/cpu)')
    parser.add_argument('--seed', type=int, default=42,
                        help='Random seed')

    return parser.parse_args()


def main():
    """Entry point for KDA model training."""
    args = parse_args()

    # Set seed
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    # Device
    if args.device is None:
        device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    else:
        device = torch.device(args.device)

    print(f"Using device: {device}")

    # Config
    config = {
        'learning_rate': args.lr,
        'weight_decay': args.weight_decay,
        'bce_weight': args.bce_weight,
        'dice_weight': args.dice_weight,
        'patience': args.patience,
        'scheduler_patience': 10,
        'grad_clip': 1.0
    }

    # Model
    model = AttentionUNet(
        in_channels=1,
        base_filters=args.base_filters,
        attention_filters=args.attention_filters,
        dropout=args.dropout
    )

    print(f"Model parameters: {model.get_num_parameters():,}")

    # Datasets
    train_dataset = KDADataset(args.data_dir, split='train')
    val_dataset = KDADataset(args.data_dir, split='val')

    print(f"Training samples: {len(train_dataset)}")
    print(f"Validation samples: {len(val_dataset)}")

    # DataLoaders
    train_loader = DataLoader(
        train_dataset,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.num_workers,
        pin_memory=True
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=True
    )

    # Trainer
    trainer = KDATrainer(
        model=model,
        train_loader=train_loader,
        val_loader=val_loader,
        config=config,
        device=device
    )

    # Train
    trainer.train(
        num_epochs=args.epochs,
        output_dir=args.output_dir
    )


if __name__ == '__main__':
    main()
