class KDATrainer:
    """
    Trainer for Attention U-Net KDA prediction model.

    Handles training loop, validation, checkpointing, and logging.

    Args:
        model: AttentionUNet instance.
        train_loader: DataLoader for training data.
        val_loader: DataLoader for validation data.
        config: Training configuration dictionary.
        device: Device for training.
    """

    def __init__(
        self,
        model: AttentionUNet,
        train_loader: DataLoader,
        val_loader: DataLoader,
        config: Dict,
        device: torch.device
    ):
        self.model = model.to(device)
        self.train_loader = train_loader
        self.val_loader = val_loader
        self.config = config
        self.device = device

        # Loss function
        self.criterion = CombinedLoss(
            bce_weight=config.get('bce_weight', 1.0),
            dice_weight=config.get('dice_weight', 1.0)
        )

        # Optimizer
        self.optimizer = optim.Adam(
            model.parameters(),
            lr=config.get('learning_rate', 1e-4),
            weight_decay=config.get('weight_decay', 1e-5)
        )

        # Learning rate scheduler
        self.scheduler = optim.lr_scheduler.ReduceLROnPlateau(
            self.optimizer,
            mode='min',
            patience=config.get('scheduler_patience', 10),
            factor=0.5,
            min_lr=1e-7
        )

        # Training state
        self.current_epoch = 0
        self.best_val_loss = float('inf')
        self.best_val_dice = 0.0
        self.early_stop_counter = 0
        self.history = {
            'train_loss': [],
            'val_loss': [],
            'val_dice': [],
            'learning_rate': []
        }

    def train_epoch(self) -> Dict[str, float]:
        """
        Train for one epoch.

        Returns:
            Dictionary of training metrics.
        """
        self.model.train()
        total_loss = 0.0
        total_bce = 0.0
        total_dice = 0.0
        num_batches = 0

        pbar = tqdm(self.train_loader, desc=f"Epoch {self.current_epoch + 1} [Train]")

        for batch_idx, (masks, kda_targets) in enumerate(pbar):
            masks = masks.to(self.device)
            kda_targets = kda_targets.to(self.device)

            # Forward pass
            self.optimizer.zero_grad()
            predictions = self.model(masks)

            # Compute loss
            loss, loss_dict = self.criterion(predictions, kda_targets)

            # Backward pass
            loss.backward()

            # Gradient clipping
            torch.nn.utils.clip_grad_norm_(
                self.model.parameters(),
                max_norm=self.config.get('grad_clip', 1.0)
            )

            self.optimizer.step()

            # Accumulate metrics
            total_loss += loss_dict['total']
            total_bce += loss_dict['bce']
            total_dice += loss_dict['dice']
            num_batches += 1

            # Update progress bar
            pbar.set_postfix({
                'loss': f"{loss_dict['total']:.4f}",
                'dice_loss': f"{loss_dict['dice']:.4f}"
            })

        metrics = {
            'loss': total_loss / num_batches,
            'bce': total_bce / num_batches,
            'dice_loss': total_dice / num_batches
        }

        return metrics

    def validate(self) -> Dict[str, float]:
        """
        Validate on validation set.

        Returns:
            Dictionary of validation metrics.
        """
        self.model.eval()
        total_loss = 0.0
        total_dice_score = 0.0
        num_batches = 0

        with torch.no_grad():
            pbar = tqdm(self.val_loader, desc=f"Epoch {self.current_epoch + 1} [Val]")

            for masks, kda_targets in pbar:
                masks = masks.to(self.device)
                kda_targets = kda_targets.to(self.device)

                predictions = self.model(masks)
                loss, loss_dict = self.criterion(predictions, kda_targets)

                # Compute Dice score (1 - Dice loss)
                dice_score = 1.0 - loss_dict['dice']

                total_loss += loss_dict['total']
                total_dice_score += dice_score
                num_batches += 1

                pbar.set_postfix({
                    'loss': f"{loss_dict['total']:.4f}",
                    'dice': f"{dice_score:.4f}"
                })

        metrics = {
            'loss': total_loss / num_batches,
            'dice': total_dice_score / num_batches
        }

        return metrics

    def train(
        self,
        num_epochs: int,
        output_dir: str,
        save_every: int = 10
    ):
        """
        Full training loop.

        Args:
            num_epochs: Number of training epochs.
            output_dir: Directory to save checkpoints.
            save_every: Save checkpoint every N epochs.
        """
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        patience = self.config.get('patience', 20)

        print(f"Starting training for {num_epochs} epochs")
        print(f"Device: {self.device}")
        print(f"Model parameters: {self.model.get_num_parameters():,}")

        for epoch in range(num_epochs):
            self.current_epoch = epoch

            # Train
            train_metrics = self.train_epoch()

            # Validate
            val_metrics = self.validate()

            # Update scheduler
            self.scheduler.step(val_metrics['loss'])
            current_lr = self.optimizer.param_groups[0]['lr']

            # Log metrics
            self.history['train_loss'].append(train_metrics['loss'])
            self.history['val_loss'].append(val_metrics['loss'])
            self.history['val_dice'].append(val_metrics['dice'])
            self.history['learning_rate'].append(current_lr)

            print(f"\nEpoch {epoch + 1}/{num_epochs}")
            print(f"  Train Loss: {train_metrics['loss']:.4f}")
            print(f"  Val Loss: {val_metrics['loss']:.4f}, Val Dice: {val_metrics['dice']:.4f}")
            print(f"  Learning Rate: {current_lr:.2e}")

            # Save best model
            is_best = val_metrics['dice'] > self.best_val_dice
            if is_best:
                self.best_val_dice = val_metrics['dice']
                self.best_val_loss = val_metrics['loss']
                self.early_stop_counter = 0

                self._save_checkpoint(
                    output_dir / 'kda_best.pth',
                    is_best=True
                )
                print(f"  New best model saved! Dice: {self.best_val_dice:.4f}")
            else:
                self.early_stop_counter += 1

            # Save periodic checkpoint
            if (epoch + 1) % save_every == 0:
                self._save_checkpoint(
                    output_dir / f'kda_epoch_{epoch + 1}.pth'
                )

            # Early stopping
            if self.early_stop_counter >= patience:
                print(f"\nEarly stopping triggered after {patience} epochs without improvement")
                break

        # Save final model
        self._save_checkpoint(output_dir / 'kda_final.pth')

        # Save training history
        with open(output_dir / 'training_history.json', 'w') as f:
            json.dump(self.history, f, indent=2)

        print(f"\nTraining completed!")
        print(f"Best validation Dice: {self.best_val_dice:.4f}")

    def _save_checkpoint(
        self,
        path: Path,
        is_best: bool = False
    ):
        """Save model checkpoint."""
        checkpoint = {
            'model_state_dict': self.model.state_dict(),
            'optimizer_state_dict': self.optimizer.state_dict(),
            'scheduler_state_dict': self.scheduler.state_dict(),
            'epoch': self.current_epoch,
            'best_val_loss': self.best_val_loss,
            'best_val_dice': self.best_val_dice,
            'config': self.config
        }
        torch.save(checkpoint, path)


