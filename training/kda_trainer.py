# Loss Functions
# =============================================================================

class DiceLoss(nn.Module):
    """
    Dice Loss for binary segmentation.

    Dice = 2 * |X ∩ Y| / (|X| + |Y|)
    Loss = 1 - Dice

    Args:
        smooth: Smoothing factor to avoid division by zero.
    """

    def __init__(self, smooth: float = 1e-6):
        super(DiceLoss, self).__init__()
        self.smooth = smooth

    def forward(
        self,
        pred: torch.Tensor,
        target: torch.Tensor
    ) -> torch.Tensor:
        """
        Compute Dice loss.

        Args:
            pred: Predicted probabilities, shape (B, 1, H, W).
            target: Ground truth mask, shape (B, 1, H, W).

        Returns:
            Dice loss value.
        """
        pred_flat = pred.view(-1)
        target_flat = target.view(-1)

        intersection = (pred_flat * target_flat).sum()
        union = pred_flat.sum() + target_flat.sum()

        dice = (2.0 * intersection + self.smooth) / (union + self.smooth)
        return 1.0 - dice


class CombinedLoss(nn.Module):
    """
    Combined BCE + Dice Loss for KDA prediction.

    L_total = bce_weight * BCE + dice_weight * Dice

    Args:
        bce_weight: Weight for BCE loss.
        dice_weight: Weight for Dice loss.
    """

    def __init__(
        self,
        bce_weight: float = 1.0,
        dice_weight: float = 1.0
    ):
        super(CombinedLoss, self).__init__()

        self.bce_weight = bce_weight
        self.dice_weight = dice_weight

        self.bce_loss = nn.BCELoss()
        self.dice_loss = DiceLoss()

    def forward(
        self,
        pred: torch.Tensor,
        target: torch.Tensor
    ) -> Tuple[torch.Tensor, Dict[str, float]]:
        """
        Compute combined loss.

        Args:
            pred: Predicted probabilities.
            target: Ground truth mask.

        Returns:
            Tuple of (total_loss, loss_dict).
        """
        bce = self.bce_loss(pred, target)
        dice = self.dice_loss(pred, target)

        total = self.bce_weight * bce + self.dice_weight * dice

        loss_dict = {
            'bce': bce.item(),
            'dice': dice.item(),
            'total': total.item()
        }

        return total, loss_dict


