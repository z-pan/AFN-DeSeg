class KDADataset(Dataset):
    """
    Dataset for KDA prediction training.

    Loads nuclear segmentation masks and corresponding KDA annotations.

    Args:
        data_dir: Directory containing the data.
        split: Data split ('train', 'val', 'test').
        transform: Optional transforms to apply.
    """

    def __init__(
        self,
        data_dir: str,
        split: str = 'train',
        transform: Optional[callable] = None
    ):
        self.data_dir = Path(data_dir)
        self.split = split
        self.transform = transform

        # Paths to data subdirectories
        self.masks_dir = self.data_dir / 'nuclear_masks'
        self.kda_dir = self.data_dir / 'kda_annotations'

        # Load file list
        self.samples = self._load_samples()

    def _load_samples(self) -> List[Tuple[Path, Path]]:
        """Load list of sample pairs (mask, kda)."""
        samples = []

        # Try to load split file
        split_file = self.data_dir / f'{self.split}.txt'
        if split_file.exists():
            with open(split_file, 'r') as f:
                filenames = [line.strip() for line in f if line.strip()]
        else:
            # Use all files
            filenames = [p.stem for p in self.masks_dir.glob('*.npy')]
            # Simple split
            n = len(filenames)
            if self.split == 'train':
                filenames = filenames[:int(0.7 * n)]
            elif self.split == 'val':
                filenames = filenames[int(0.7 * n):int(0.85 * n)]
            else:
                filenames = filenames[int(0.85 * n):]

        for name in filenames:
            mask_path = self.masks_dir / f'{name}.npy'
            kda_path = self.kda_dir / f'{name}.npy'

            if mask_path.exists() and kda_path.exists():
                samples.append((mask_path, kda_path))

        return samples

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        mask_path, kda_path = self.samples[idx]

        # Load data
        mask = np.load(mask_path).astype(np.float32)
        kda = np.load(kda_path).astype(np.float32)

        # Ensure binary
        mask = (mask > 0.5).astype(np.float32)
        kda = (kda > 0.5).astype(np.float32)

        # Apply transforms
        if self.transform is not None:
            augmented = self.transform(image=mask, mask=kda)
            mask = augmented['image']
            kda = augmented['mask']

        # Convert to tensor
        mask = torch.from_numpy(mask).unsqueeze(0)  # (1, H, W)
        kda = torch.from_numpy(kda).unsqueeze(0)    # (1, H, W)

        return mask, kda


